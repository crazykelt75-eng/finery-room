SIZES = {
    "9x16": dict(w=1080, h=1920, logo=130, hook=92, lgap=8, line=44, sub=24, cta=38, ctap=24, ctapx=46),
    "1x1": dict(w=1080, h=1080, logo=96, hook=64, lgap=6, line=32, sub=18, cta=30, ctap=18, ctapx=30),
}


def page(ad, fmt):
    s = SIZES[fmt]
    lines = "".join(f"<span>{l}</span>" for l in ad["lines"])
    logo = f'<img class="logo" src="{LOGO}" alt="">'
    sub = '<div class="sub">Finery Room · Tati Siding</div>'
    if fmt == "9x16":
        photo = (f'<div class="photo"><img src="{(C / (ad["photo"] + "-1x1.png")).as_uri()}" alt=""></div>'
                 if ad["photo"] else '<div class="nophoto"></div>')
        body = (f'<div class="wrap">{logo}<h1>{ad["hook"]}</h1>{photo}<div class="lines">{lines}</div>{sub}'
                f'<div class="cta">Book on WhatsApp {PHONE}</div></div>')
        css = BASE % s + TALL
    else:
        cta = f'<div class="cta">Book on WhatsApp<br>{PHONE}</div>'
        if ad["photo"]:
            photo = f'<div class="photo"><img src="{(C / (ad["photo"] + "-4x5.png")).as_uri()}" alt=""></div>'
            body = (f'<div class="wrap">{photo}<div class="text">{logo}<h1>{ad["hook"]}</h1>'
                    f'<div class="lines">{lines}</div>{sub}<div>{cta}</div></div></div>')
        else:
            body = (f'<div class="wrap"><div class="text full">{logo}<h1>{ad["hook"]}</h1>'
                    f'<div class="lines">{lines}</div>{sub}<div>{cta}</div></div></div>')
        css = BASE % s + SQUARE
    return f'<!doctype html><html><head><meta charset="utf-8">{FONTS}<style>{css}</style></head><body>{body}</body></html>'


