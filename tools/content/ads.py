def render(html, w, h, png):
    src = WORK / (png.stem + ".html")
    src.write_text(html, encoding="utf-8")
    subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars",
                    "--allow-file-access-from-files", "--virtual-time-budget=8000",
                    f"--window-size={w},{h}", f"--screenshot={png}", src.as_uri()],
                   check=True, capture_output=True, timeout=90)
    return Image.open(png).convert("RGB")


if __name__ == "__main__":
    for name, ad in ADS.items():
        for fmt, s in SIZES.items():
            png = WORK / f"ad-{name}-{fmt}.png"
            img = render(page(ad, fmt), s["w"], s["h"], png)
            dest = OUT / f"ad-{name}-{fmt}.jpg"
            img.save(dest, quality=88, optimize=True, progressive=True)
            print(dest.relative_to(REPO), img.size, dest.stat().st_size // 1024, "KB", flush=True)
    img = render(share_page(), 1200, 630, WORK / "share-1200x630.png")
    dest = REPO / "assets" / "img" / "share-1200x630.jpg"
